#!/usr/bin/env python3
"""Build the claude-directory branch: the Claude plugin from a commit on main, without this repository's scripts.

The Claude plugin directory reads one branch of this repository from its root. From an organisation it has not
verified, it accepts only Markdown, text, JSON, YAML and PNG/JPEG/GIF/WebP/ICO files, so it refuses main, which
keeps the manifest generator and checks in scripts/. This script copies only what Claude Code loads, plus the
readme, licence and .gitignore, from a commit into a new commit on the claude-directory branch, and refuses to
build if any copied file is outside that list.
"""
import argparse
import os
import subprocess
import tempfile
from pathlib import Path

import platforms

ROOT = Path(__file__).resolve().parents[1]
BRANCH = 'claude-directory'
REMOTE = 'origin'
REPOSITORY = platforms.REPOSITORY
# Copied paths. Folders are copied whole; each one must exist in the source commit.
PATHS = ('.claude-plugin/plugin.json', '.claude-plugin/marketplace.json', '.mcp.json', platforms.LOGO[2:],
         'README.md', 'LICENSE', '.gitignore') + tuple(path[2:] for path in platforms.CLAUDE_SKILL_PATHS)
TEXT = ('.md', '.txt', '.json', '.yaml', '.yml')
IMAGES = ('.png', '.jpg', '.jpeg', '.gif', '.webp', '.ico')
TEXT_NAMES = ('LICENSE', '.gitignore')


def git(root, *args, data=None, env=None):
    return subprocess.run(('git',) + args, cwd=root, input=data, env=env, capture_output=True, check=True).stdout


def resolve(root, ref):
    found = subprocess.run(('git', 'rev-parse', '--verify', '--quiet', ref + '^{commit}'), cwd=root,
                           capture_output=True)
    return found.stdout.decode().strip() if found.returncode == 0 else None


def entries(root, source):
    """List the copied files in the source commit as (mode, type, object, path)."""
    listed = git(root, 'ls-tree', '-r', '-z', '--full-tree', source, '--', *PATHS)
    rows = []
    for line in listed.decode().split('\0'):
        if line:
            meta, path = line.split('\t', 1)
            rows.append(tuple(meta.split(' ')) + (path,))
    for path in PATHS:
        if not any(row[3] == path or row[3].startswith(path + '/') for row in rows):
            raise ValueError('Missing from ' + source + ': ' + path)
    return rows


def refuse(path, mode, content):
    """Return why the directory would refuse this file from an organisation it has not verified, or None."""
    name = path.rsplit('/', 1)[-1]
    text = name in TEXT_NAMES or name.lower().endswith(TEXT)
    if mode != '100644':
        return 'not a plain file (mode ' + mode + ')'
    if not text and not name.lower().endswith(IMAGES):
        return 'not Markdown, text, JSON, YAML or an allowed image'
    if content.startswith(b'#!'):
        return 'starts with #!'
    if text:
        if b'\0' in content:
            return 'holds a NUL byte'
        try:
            content.decode('utf-8')
        except UnicodeDecodeError:
            return 'is not UTF-8'
    return None


def build(root=ROOT, source='HEAD', parent=None):
    """Commit the Claude plugin from source onto parent, or return parent when nothing changed."""
    source = resolve(root, source) or ''
    if not source:
        raise ValueError('Unknown source commit')
    rows = entries(root, source)
    problems = []
    for mode, kind, obj, path in rows:
        content = git(root, 'cat-file', 'blob', obj) if kind == 'blob' else b''
        reason = refuse(path, mode, content) if kind == 'blob' else 'not a file (' + kind + ')'
        if reason:
            problems.append(path + ': ' + reason)
    if problems:
        raise ValueError('The Claude plugin directory would refuse:\n' + '\n'.join(problems))
    with tempfile.TemporaryDirectory() as directory:
        env = dict(os.environ, GIT_INDEX_FILE=str(Path(directory) / 'index'))
        info = ''.join('{} {} {}\t{}\0'.format(*row) for row in rows)
        git(root, 'update-index', '-z', '--index-info', data=info.encode(), env=env)
        tree = git(root, 'write-tree', env=env).decode().strip()
    if parent and git(root, 'rev-parse', parent + '^{tree}').decode().strip() == tree:
        return parent, sorted(row[3] for row in rows), False
    message = ('Build the Claude plugin from {short}\n\nSource: {repo}/commit/{full}\n'
               'Generated by scripts/directory.py on main. Do not edit this branch by hand.\n').format(
        short=source[:7], repo=REPOSITORY, full=source)
    args = ('commit-tree', tree, '-F', '-') + (('-p', parent) if parent else ())
    commit = git(root, *args, data=message.encode()).decode().strip()
    return commit, sorted(row[3] for row in rows), True


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', default='HEAD', help='Commit to build from (default: HEAD)')
    parser.add_argument('--push', action='store_true',
                        help='Fetch {0}/{1}, build on top of it and push the result to {1}'.format(REMOTE, BRANCH))
    args = parser.parse_args()
    tracking = 'refs/remotes/{}/{}'.format(REMOTE, BRANCH)
    try:
        if args.push:
            # A missing branch is not an error: the first build starts it.
            subprocess.run(('git', 'fetch', '--quiet', REMOTE, '+refs/heads/{}:{}'.format(BRANCH, tracking)),
                           cwd=ROOT, capture_output=True)
        parent = resolve(ROOT, tracking)
        commit, files, created = build(ROOT, args.source, parent)
        if args.push and commit != parent:
            git(ROOT, 'push', '--quiet', REMOTE, commit + ':refs/heads/' + BRANCH)
            git(ROOT, 'update-ref', tracking, commit)
    except ValueError as error:
        parser.exit(1, str(error) + '\n')
    except subprocess.CalledProcessError as error:
        parser.exit(1, ' '.join(error.cmd) + ' failed:\n' + error.stderr.decode(errors='replace'))
    state = 'built {}{}'.format(commit[:7], ' and pushed' if args.push else '') if created else \
        'already current at ' + commit[:7]
    print('{}: {} ({} files: {})'.format(BRANCH, state, len(files), ', '.join(files)))


if __name__ == '__main__':
    main()
