import os
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path
from unittest import mock

import directory
import platforms

ROOT = directory.ROOT
CLAUDE_FILES = sorted(
    ['.claude-plugin/marketplace.json', '.claude-plugin/plugin.json', '.gitignore', '.mcp.json', 'LICENSE',
     'README.md', platforms.LOGO[2:]]
    + [str(path.relative_to(ROOT)) for name in platforms.CLAUDE_SKILLS
       for path in (ROOT / 'skills' / name).rglob('*') if path.is_file()])


class DirectoryBranch(unittest.TestCase):
    def setUp(self):
        self.directory = tempfile.TemporaryDirectory()
        self.addCleanup(self.directory.cleanup)
        self.root = Path(self.directory.name) / 'repo'
        config = Path(self.directory.name) / 'gitconfig'
        config.write_text('')
        environment = mock.patch.dict(os.environ, {
            'GIT_CONFIG_GLOBAL': str(config), 'GIT_CONFIG_NOSYSTEM': '1',
            'GIT_AUTHOR_NAME': 'Test', 'GIT_AUTHOR_EMAIL': 'test@example.invalid',
            'GIT_COMMITTER_NAME': 'Test', 'GIT_COMMITTER_EMAIL': 'test@example.invalid'})
        environment.start()
        self.addCleanup(environment.stop)
        shutil.copytree(ROOT / 'skills', self.root / 'skills')
        shutil.copytree(ROOT / 'assets', self.root / 'assets')
        shutil.copytree(ROOT / 'scripts', self.root / 'scripts', ignore=shutil.ignore_patterns('__pycache__'))
        for name in ('README.md', 'LICENSE', '.gitignore', 'AGENTS.md'):
            shutil.copy(ROOT / name, self.root / name)
        platforms.write(self.root)
        self.git('init', '-q')
        self.commit()

    def git(self, *args):
        return subprocess.run(('git',) + args, cwd=self.root, capture_output=True, check=True).stdout.decode()

    def commit(self):
        self.git('add', '-A')
        self.git('commit', '-q', '-m', 'change')
        return self.git('rev-parse', 'HEAD').strip()

    def test_branch_holds_only_the_claude_plugin_and_rebuilds_only_on_change(self):
        commit, files, created = directory.build(self.root)
        self.assertTrue(created)
        self.assertEqual(CLAUDE_FILES, files)
        self.assertEqual(CLAUDE_FILES, sorted(self.git('ls-tree', '-r', '--name-only', commit).split()))
        self.assertIn('Generated by scripts/directory.py', self.git('log', '-1', '--format=%B', commit))
        (self.root / 'scripts/platforms.py').write_text('# only the generator changed\n')
        self.commit()
        self.assertEqual((commit, files, False), directory.build(self.root, parent=commit))
        entry = self.root / 'skills/website-feedback/SKILL.md'
        entry.write_text(entry.read_text() + '\nOne more line.\n')
        source = self.commit()
        rebuilt, _, created = directory.build(self.root, parent=commit)
        self.assertTrue(created)
        self.assertEqual(commit, self.git('log', '-1', '--format=%P', rebuilt).strip())
        self.assertIn('/commit/' + source + '\n', self.git('log', '-1', '--format=%B', rebuilt))

    def test_files_the_directory_refuses_stop_the_build(self):
        skill = self.root / 'skills/website-feedback'
        cases = {
            'run.py: not Markdown': lambda: (skill / 'run.py').write_text('print(1)\n'),
            'notes.md: starts with #!': lambda: (skill / 'notes.md').write_text('#!/bin/sh\n'),
            r'SKILL.md: not a plain file \(mode 100755\)': lambda: (skill / 'SKILL.md').chmod(0o755),
            r'link.md: not a plain file \(mode 120000\)': lambda: (skill / 'link.md').symlink_to('SKILL.md'),
            'notes.md: holds a NUL byte': lambda: (skill / 'notes.md').write_bytes(b'text\0'),
            'notes.md: is not UTF-8': lambda: (skill / 'notes.md').write_bytes(b'\xff\xfe'),
            'Missing from [0-9a-f]+: LICENSE': lambda: (self.root / 'LICENSE').unlink(),
        }
        clean = self.git('rev-parse', 'HEAD').strip()
        for case, change in cases.items():
            with self.subTest(case=case):
                self.git('reset', '-q', '--hard', clean)
                self.git('clean', '-qfd')
                change()
                self.commit()
                with self.assertRaisesRegex(ValueError, case):
                    directory.build(self.root)

    def test_this_repository_builds(self):
        _, files, _ = directory.build(ROOT)
        self.assertEqual(CLAUDE_FILES, files)


if __name__ == '__main__':
    unittest.main()
